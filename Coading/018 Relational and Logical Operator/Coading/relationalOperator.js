
// Relational Operator
// >, >=, <, <=, ==, ===, !=, !==

var num1 = 20;
var num2 = 10;

// Greater than (বড় কি না)
console.log(num1 > num2);  

// Greater than or equal (বড় অথবা সমান কি না)
console.log(num1 >= num2);   

// Less than (ছোট কি না)
console.log(num1 < num2);   

// Less than or equal (ছোট অথবা সমান কি না)
console.log(num1 <= num2);    

// Equal (শুধু Value সমান কি না পরীক্ষা করে)
console.log(20 == "20"); 

// Strict Equal (Value এবং Data Type দুটোই পরীক্ষা করে)
console.log(20 === "20");   

// Not Equal (Value সমান নয় কি না)
console.log(20 != 10);     

// Strict Not Equal (Value অথবা Data Type আলাদা কি না)
console.log(20 !== "20");    
